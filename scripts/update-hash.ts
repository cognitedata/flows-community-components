#!/usr/bin/env node

/**
 * Updates the hash for a specific component's metadata file
 * Usage: tsx scripts/update-hash.ts <component-name>
 * Example: tsx scripts/update-hash.ts inline-citation
 */

import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';
import { createHash } from 'crypto';

// Get __dirname equivalent in ES modules
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Generate MD5 hash of file content
export function generateFileHash(filePath: string): string {
  const content = fs.readFileSync(filePath, 'utf8');
  return createHash('md5').update(content).digest('hex');
}

// Get existing status from metadata file, or default to 'draft'
export function getExistingStatus(metadataPath: string): 'draft' | 'production' {
  if (!fs.existsSync(metadataPath)) {
    return 'draft'; // default for new components
  }

  try {
    const content = fs.readFileSync(metadataPath, 'utf8');
    const match = content.match(/status:\s*'(\w+)'/);
    if (match) {
      const status = match[1].toLowerCase();
      if (status === 'production') return 'production';
      if (status === 'draft') return 'draft';
    }
  } catch {
    console.warn(`⚠️  Could not read existing metadata: ${metadataPath}`);
  }

  return 'draft'; // fallback
}

// Generate metadata file for a component
export function updateComponentHash(componentName: string): boolean {
  const componentPath = path.join(
    __dirname,
    '..',
    'src',
    'components',
    'ui',
    'cognite',
    `${componentName}.tsx`
  );
  const metadataPath = path.join(
    __dirname,
    '..',
    'src',
    'components',
    'ui',
    'cognite',
    `${componentName}.metadata.ts`
  );

  if (!fs.existsSync(componentPath)) {
    console.error(`❌ Component file not found: ${componentPath}`);
    return false;
  }

  const hash = generateFileHash(componentPath);
  // Preserve existing status, or default to 'draft' for new components
  const status = getExistingStatus(metadataPath);

  const metadataContent = `// 'hash' is auto-generated by build-registry.ts or hash:update and should not be edited manually
// 'status' should be edited manually, and indicates whether this component is in 'draft' or 'production'
export const metadata = {
  hash: '${hash}',
  status: '${status}' as const,
};
`;

  fs.writeFileSync(metadataPath, metadataContent);
  return true;
}

// Get all components from ui/cognite directory
function getAllComponents(): string[] {
  const uiCogniteDir = path.join(
    __dirname,
    '..',
    'src',
    'components',
    'ui',
    'cognite'
  );

  const components: string[] = [];

  if (fs.existsSync(uiCogniteDir)) {
    const uiFiles = fs
      .readdirSync(uiCogniteDir)
      .filter((file: string) => file.endsWith('.tsx'))
      .map((file: string) => file.replace('.tsx', ''));

    components.push(...uiFiles);
  }

  return components;
}

// Main execution when run directly
async function main(): Promise<void> {
  const componentName = process.argv[2];

  // If no component name provided, update all components
  if (!componentName) {
    console.log('\n🔨 Updating hashes for all components...\n');

    const components = getAllComponents();

    if (components.length === 0) {
      console.error('❌ No components found in src/components/ui/cognite/\n');
      process.exit(1);
    }

    console.log(`Found ${components.length} component(s)\n`);

    let successCount = 0;
    let failCount = 0;

    for (const comp of components) {
      const success = updateComponentHash(comp);
      if (success) {
        successCount++;
      } else {
        failCount++;
      }
    }

    console.log(`\n✅ Successfully updated ${successCount} hash(es)`);
    if (failCount > 0) {
      console.log(`❌ Failed to update ${failCount} hash(es)`);
    }
    console.log('');

    process.exit(failCount > 0 ? 1 : 0);
  }

  // Update single component
  console.log(`\n🔨 Updating hash for: ${componentName}`);

  const success = updateComponentHash(componentName);

  if (success) {
    console.log(`✅ Successfully updated hash for ${componentName}\n`);
  } else {
    console.log(`\n❌ Failed to update hash for ${componentName}\n`);
    process.exit(1);
  }
}

// Only run main if this file is being executed directly
if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}

